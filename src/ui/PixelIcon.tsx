function dims(grid: readonly string[]) {
  return { w: Math.max(...grid.map((r) => r.length)), h: grid.length }
}

/** Ícono como componente React. Si el nombre no existe no pinta nada (nunca un emoji). */
export function PixelIcon(p: { name: PixelIconName | string; size?: number; title?: string; className?: string }) {
  if (!isPixelIcon(p.name)) return null
  const grid = GRIDS[p.name]
  const s = p.size ?? 16
  const { w, h } = dims(grid)
  const m = Math.max(w, h)
  return (
    <svg
      width={(s * w) / m}
      height={(s * h) / m}
      viewBox={`0 0 ${w} ${h}`}
      className={p.className ? `px-icon ${p.className}` : 'px-icon'}
      role={p.title ? 'img' : undefined}
      aria-label={p.title}
      aria-hidden={p.title ? undefined : true}
      focusable="false"
      shapeRendering="crispEdges"
    >
      {p.title ? <title>{p.title}</title> : null}
      {gridRuns(grid).map((r) => {
        const fill = PAL[r.ch]
        return fill ? <rect key={`${r.x}_${r.y}`} x={r.x} y={r.y} width={r.w} height={1} style={{ fill }} /> : null
      })}
    </svg>
  )
}

const svgCache = new Map<string, string>()

/** Mismo ícono como string SVG (para APIs imperativas como toast()) */
export function pixelIconSvg(name: PixelIconName | string, size = 16): string {
  if (!isPixelIcon(name)) return ''
  const key = `${name}@${size}`
  const hit = svgCache.get(key)
  if (hit) return hit
  const grid = GRIDS[name]
  const { w, h } = dims(grid)
  const m = Math.max(w, h)
  let rects = ''
  for (const r of gridRuns(grid)) {
    const fill = PAL[r.ch]
    if (fill) rects += `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="1" style="fill:${fill}"/>`
  }
  const out =
    `<svg class="px-icon" width="${(size * w) / m}" height="${(size * h) / m}" viewBox="0 0 ${w} ${h}" ` +
    `shape-rendering="crispEdges" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg">${rects}</svg>`
  svgCache.set(key, out)
  return out
}

export default PixelIcon
